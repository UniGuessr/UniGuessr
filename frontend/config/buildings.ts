/**
 * A campus building outline highlighted on the map. Purely visual — these have
 * no floor-bonus / gameplay role (that lives in BUILDINGS_WITH_FLOORS).
 */
export interface CampusBuildingOutline {
  id: string;
  /** Short badge label shown over the footprint, e.g. "Hall", "CC". */
  label: string;
  /** Full building name. */
  name: string;
  /** Footprint centroid, used to place the label. */
  latitude: number;
  longitude: number;
  /** Closed ring of [lng, lat] points (from OSM). */
  footprint: [number, number][];
}

